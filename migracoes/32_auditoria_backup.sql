-- =====================================================================
-- Migração 32 — Lixeira/auditoria + registro de backups. Idempotente
-- (pode rodar mais de uma vez). Rodar no SQL Editor do Supabase do ERP.
--
-- 1) auditoria_exclusoes: cópia (JSON) de toda linha APAGADA ou ALTERADA nas
--    tabelas importantes — quem, quando, de onde. Permite restaurar.
-- 2) Gatilhos no banco: valem para TUDO (telas, robô, SQL Editor), não só
--    para o que passa pelo app.
-- 3) Bloqueio de TRUNCATE nas tabelas de dinheiro/cadastro (um "apagar tudo"
--    acidental passa a dar erro em vez de zerar a tabela).
-- 4) backups_erp: registro de cada backup feito pelo robô (data, linhas por
--    tabela, ok/erro) — é o "Último backup" mostrado em Configurações.
-- =====================================================================

create table if not exists public.auditoria_exclusoes (
    id              bigint generated by default as identity primary key,
    tabela          text        not null,
    operacao        text        not null,              -- DELETE | UPDATE
    registro_id     text,
    dados           jsonb,                              -- linha como era ANTES
    dados_novos     jsonb,                              -- (UPDATE) como ficou
    quem            text,
    origem          text        not null default 'db',  -- db (gatilho) | app (tela, com motivo)
    motivo          text,
    criado_em       timestamptz not null default now(),
    restaurado_em   timestamptz,
    restaurado_por  text
);
create index if not exists idx_auditoria_tab_data on public.auditoria_exclusoes (tabela, criado_em desc);
create index if not exists idx_auditoria_op_data  on public.auditoria_exclusoes (operacao, criado_em desc);
create index if not exists idx_auditoria_reg      on public.auditoria_exclusoes (tabela, registro_id);

-- A lixeira não se apaga nem se altera (só a marca de "restaurado").
create or replace function public.auditoria_protege() returns trigger language plpgsql as $$
begin
    if tg_op = 'DELETE' then
        raise exception 'A lixeira (auditoria_exclusoes) não pode ser apagada';
    end if;
    if new.tabela is distinct from old.tabela or new.operacao is distinct from old.operacao
       or new.registro_id is distinct from old.registro_id or new.dados is distinct from old.dados
       or new.dados_novos is distinct from old.dados_novos or new.criado_em is distinct from old.criado_em
       or new.quem is distinct from old.quem or new.origem is distinct from old.origem then
        raise exception 'Registro da lixeira não pode ser alterado (só marcar como restaurado)';
    end if;
    return new;
end $$;
drop trigger if exists trg_auditoria_protege on public.auditoria_exclusoes;
create trigger trg_auditoria_protege before update or delete on public.auditoria_exclusoes
    for each row execute function public.auditoria_protege();

-- Gatilho genérico: guarda a linha antiga (e a nova, no UPDATE). Senhas nunca entram.
create or replace function public.auditoria_registra() returns trigger language plpgsql
security definer set search_path = public as $$
declare
    v_old jsonb;
    v_new jsonb;
    v_quem text;
begin
    v_old := to_jsonb(old) - 'senha' - 'senha_hash';
    if tg_op = 'UPDATE' then
        v_new := to_jsonb(new) - 'senha' - 'senha_hash';
        if v_new = v_old then
            return new;                     -- nada mudou de verdade
        end if;
    end if;
    begin
        v_quem := coalesce(nullif(current_setting('request.jwt.claims', true), '')::jsonb ->> 'role', current_user);
    exception when others then
        v_quem := current_user;
    end;
    insert into public.auditoria_exclusoes (tabela, operacao, registro_id, dados, dados_novos, quem, origem)
    values (tg_table_name, tg_op, v_old ->> 'id', v_old, v_new, v_quem, 'db');
    if tg_op = 'DELETE' then
        return old;
    end if;
    return new;
end $$;

-- UPDATE + DELETE nas tabelas de vendas/clientes/comissões
do $$
declare t text;
begin
    foreach t in array array['vendas', 'clientes', 'comissoes_pagas', 'status_comissoes'] loop
        if to_regclass('public.' || t) is not null then
            execute format('drop trigger if exists trg_auditoria_%1$s on public.%1$I', t);
            execute format('create trigger trg_auditoria_%1$s after update or delete on public.%1$I '
                           'for each row execute function public.auditoria_registra()', t);
        end if;
    end loop;
    -- só DELETE nas demais (UPDATE delas é rotina: login, status do robô...)
    foreach t in array array['administradoras', 'cad_administradoras', 'config_interna', 'assembleias',
                             'usuarios', 'fila_automacao', 'midias', 'financeiro_datas',
                             'base_conhecimento_ia', 'resultado_socios_mensal'] loop
        if to_regclass('public.' || t) is not null then
            execute format('drop trigger if exists trg_auditoria_%1$s on public.%1$I', t);
            execute format('create trigger trg_auditoria_%1$s after delete on public.%1$I '
                           'for each row execute function public.auditoria_registra()', t);
        end if;
    end loop;
end $$;

-- config_interna: alteração das regras também fica registrada
do $$
begin
    if to_regclass('public.config_interna') is not null then
        drop trigger if exists trg_auditoria_config_interna on public.config_interna;
        create trigger trg_auditoria_config_interna after update or delete on public.config_interna
            for each row execute function public.auditoria_registra();
    end if;
    if to_regclass('public.administradoras') is not null then
        drop trigger if exists trg_auditoria_administradoras on public.administradoras;
        create trigger trg_auditoria_administradoras after update or delete on public.administradoras
            for each row execute function public.auditoria_registra();
    end if;
end $$;

-- TRUNCATE (apagar a tabela inteira de uma vez) proibido nas tabelas essenciais
create or replace function public.auditoria_sem_truncate() returns trigger language plpgsql as $$
begin
    raise exception 'TRUNCATE bloqueado em % (proteção de dados — migração 32)', tg_table_name;
end $$;
do $$
declare t text;
begin
    foreach t in array array['vendas', 'clientes', 'comissoes_pagas', 'status_comissoes',
                             'administradoras', 'config_interna', 'usuarios', 'auditoria_exclusoes'] loop
        if to_regclass('public.' || t) is not null then
            execute format('drop trigger if exists trg_sem_truncate_%1$s on public.%1$I', t);
            execute format('create trigger trg_sem_truncate_%1$s before truncate on public.%1$I '
                           'for each statement execute function public.auditoria_sem_truncate()', t);
        end if;
    end loop;
end $$;

-- Registro dos backups (o robô grava uma linha por backup)
create table if not exists public.backups_erp (
    id            bigint generated by default as identity primary key,
    criado_em     timestamptz not null default now(),
    origem        text,                 -- CRON | ERP (botão) | manual
    ok            boolean not null default false,
    pasta         text,
    total_linhas  bigint,
    tabelas       jsonb,                -- {"vendas": 2000, ...}
    mensagem      text,
    duracao_s     numeric
);
create index if not exists idx_backups_erp_data on public.backups_erp (criado_em desc);
